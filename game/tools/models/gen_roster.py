# Build roster-data.js from roster.json and model reports.
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.normpath(os.path.join(HERE, '..', '..'))
KEYS = ('id', 'name', 'role', 'file', 'author', 'source', 'license', 'credit', 'tris', 'rig', 'notes')
def js(v):
    if isinstance(v, str):
        return "'" + v.replace('\\', '\\\\').replace("'", "\\'") + "'"
    if isinstance(v, dict):
        return '{ ' + ', '.join('%s: %s' % (k, js(x)) for k, x in v.items()) + ' }'
    return json.dumps(v)

rows, skipped = [], []
for e in json.load(open(os.path.join(HERE, 'roster.json'), encoding='utf-8')):
    file = 'assets/models/alt/%s.glb' % e['id']
    rep = os.path.join(HERE, 'reports', e['id'] + '.json')
    if not (os.path.exists(os.path.join(GAME, file)) and os.path.exists(rep)):
        skipped.append(e['id']); continue
    d = dict(e, file=file, tris=json.load(open(rep))['tris'])
    rows.append('  { ' + ', '.join('%s: %s' % (k, js(d[k])) for k in KEYS + (('voice',) if 'voice' in d else ())) + ' },')
out = ['// Generated by game/tools/models/gen_roster.py.',
       'export const ROSTER_DATA = ['] + rows + ['];', '']
open(os.path.join(GAME, 'src', 'characters', 'roster-data.js'), 'w', encoding='utf-8').write('\n'.join(out))
print('roster-data.js:', len(rows), 'models', '| not built yet:', ' '.join(skipped))
